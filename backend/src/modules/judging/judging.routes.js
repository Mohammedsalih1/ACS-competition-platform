import { Router } from 'express';
import { authenticate } from '../../middleware/authenticate.js';
import { authorize } from '../../middleware/authorize.js';
import { validate } from '../../middleware/validate.js';
import { asyncHandler } from '../../utils/asyncHandler.js';
import { ROLES } from '../../constants/roles.js';
import * as controller from './judging.controller.js';
import { createCriterionSchema, updateCriterionSchema, criterionIdParamSchema, submissionIdParamSchema, evaluationSchema, settingSchema } from './judging.validation.js';

const router = Router();
router.use(authenticate);
router.get('/criteria', authorize(ROLES.ADMIN, ROLES.JUDGE), asyncHandler(controller.listCriteria));
router.post('/criteria', authorize(ROLES.ADMIN), validate({ body: createCriterionSchema }), asyncHandler(controller.createCriterion));
router.patch('/criteria/:criterionId', authorize(ROLES.ADMIN), validate({ params: criterionIdParamSchema, body: updateCriterionSchema }), asyncHandler(controller.updateCriterion));
router.delete('/criteria/:criterionId', authorize(ROLES.ADMIN), validate({ params: criterionIdParamSchema }), asyncHandler(controller.deleteCriterion));
router.get('/settings', authorize(ROLES.ADMIN, ROLES.JUDGE), asyncHandler(controller.getSettings));
router.patch('/settings', authorize(ROLES.ADMIN), validate({ body: settingSchema }), asyncHandler(controller.updateSettings));
router.get('/dashboard', authorize(ROLES.JUDGE), asyncHandler(controller.getDashboard));
router.get('/evaluations/mine', authorize(ROLES.JUDGE), asyncHandler(controller.listMyEvaluations));
router.put('/evaluations/:submissionId/draft', authorize(ROLES.JUDGE), validate({ params: submissionIdParamSchema, body: evaluationSchema }), asyncHandler(controller.saveDraft));
router.post('/evaluations/:submissionId/submit', authorize(ROLES.JUDGE), validate({ params: submissionIdParamSchema, body: evaluationSchema }), asyncHandler(controller.submitEvaluation));
router.get('/evaluations/:submissionId/mine', authorize(ROLES.JUDGE), validate({ params: submissionIdParamSchema }), asyncHandler(controller.getMyEvaluation));
router.get('/evaluations/:submissionId/configuration', authorize(ROLES.JUDGE), validate({ params: submissionIdParamSchema }), asyncHandler(controller.getEvaluationConfig));
router.get('/evaluations/:submissionId', authorize(ROLES.ADMIN), validate({ params: submissionIdParamSchema }), asyncHandler(controller.getEvaluationsForSubmission));
router.post('/evaluations/:submissionId/approve', authorize(ROLES.ADMIN), validate({ params: submissionIdParamSchema }), asyncHandler(controller.approveEvaluationResult));
export default router;
